import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { annotate } from '@ultralytics/yolo'
import ModelPicker from './components/ModelPicker'
import OptionsPanel from './components/OptionsPanel'
import Results from './components/Results'
import TargetOverlay from './components/TargetOverlay'
import { useDebouncedValue } from './hooks/useDebouncedValue'
import { useModel } from './hooks/useModel'
import { usePrediction } from './hooks/usePrediction'
import { analyze } from './lib/analyze'
import { drawElements } from './lib/draw'
import { pixelsOf } from './lib/pixels'
import {
  DEFAULTS,
  LOCAL_MODEL,
  analyzeOptions,
  annotateOptions,
  predictOptions,
  readSettings,
  writeSettings,
} from './lib/options'
import './App.css'

const DEFAULT_MODEL = '4p_detect_ultra_pro_max.onnx'
const SLIDER_DEBOUNCE_MS = 150

export default function App() {
  const canvasRef = useRef(null)
  // Chained so redraws run in order.
  const drawRef = useRef(Promise.resolve())

  const [settings, setSettings] = useState(readSettings)
  const [models, setModels] = useState([])
  const [localModel, setLocalModel] = useState(null)
  const [image, setImage] = useState(null)
  const [listError, setListError] = useState(null)
  const [imageError, setImageError] = useState(null)

  // ORT backend is fixed per page load; changing it requires a reload.
  const bootDevice = useRef(settings.device)

  const update = useCallback((patch) => setSettings((previous) => ({ ...previous, ...patch })), [])

  useEffect(() => {
    writeSettings(settings)
  }, [settings])

  useEffect(() => {
    if (settings.device === bootDevice.current) return
    window.location.reload()
  }, [settings.device])

  // Generated by scripts/list-models.mjs.
  useEffect(() => {
    fetch('/models/index.json')
      .then((response) => {
        if (!response.ok) throw new Error(`${response.status} ${response.statusText}`)
        return response.json()
      })
      .then((list) => {
        setModels(list)
        if (!list.length) {
          setListError(new Error('no models in public/models'))
          return
        }
        // Keep the restored model if it still exists.
        setSettings((previous) => {
          if (list.some((model) => model.file === previous.model)) return previous
          const initial = list.find((model) => model.file === DEFAULT_MODEL) ?? list[0]
          return { ...previous, model: initial.file }
        })
      })
      .catch((error) => setListError(new Error(`failed to list models: ${error.message}`)))
  }, [])

  // export_model.py sidecar for the listed model: USAF table, class names, imgsz.
  const meta = useMemo(
    () => models.find((entry) => entry.file === settings.model) ?? null,
    [models, settings.model],
  )

  const source = useMemo(() => {
    if (settings.model === LOCAL_MODEL) {
      return localModel ? { key: LOCAL_MODEL, label: localModel.name, src: localModel } : null
    }
    if (!settings.model) return null
    return { key: settings.model, label: settings.model, src: `/models/${settings.model}` }
  }, [settings.model, localModel])

  const { model, task, names, ranOn, loading, error: loadError } = useModel(source, settings.device)

  // Debounce sliders so a drag triggers one run.
  const conf = useDebouncedValue(settings.conf, SLIDER_DEBOUNCE_MS)
  const iou = useDebouncedValue(settings.iou, SLIDER_DEBOUNCE_MS)
  const classesKey = settings.classes?.join(',') ?? ''
  const predictOpts = useMemo(
    () =>
      predictOptions({
        conf,
        iou,
        classes: classesKey ? classesKey.split(',').map(Number) : null,
      }),
    [conf, iou, classesKey],
  )

  const { results, predicting, error: predictError } = usePrediction(model, image, predictOpts)

  const { labels, keypoints, keypointThreshold, lineWidth, elements, scanlines } = settings
  const annotateOpts = useMemo(
    () => annotateOptions({ labels, keypoints, keypointThreshold, lineWidth }),
    [labels, keypoints, keypointThreshold, lineWidth],
  )

  // Read once per image; everything downstream measures against this plane.
  const pixels = useMemo(() => pixelsOf(image), [image])

  const { method, threshold, rule, dipRule } = settings
  const analyzeOpts = useMemo(
    () => analyzeOptions({ keypointThreshold, method, threshold, rule, dipRule }),
    [keypointThreshold, method, threshold, rule, dipRule],
  )

  // Where the target is, what every element measured, and what that scores.
  const analysis = useMemo(
    () => analyze(results, meta?.usaf ?? null, pixels, analyzeOpts),
    [results, meta, pixels, analyzeOpts],
  )

  useEffect(() => {
    window.__dbg = { model, image, predictOpts, loading, predicting }
  })

  useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas || !image || !results) return
    drawRef.current = drawRef.current
      .then(async () => {
        await annotate(canvas, image, results, annotateOpts)
        // After annotate, which clears the canvas before redrawing the frame.
        if (elements) drawElements(canvas, analysis.elements, { labels, lineWidth, scanlines })
      })
      .catch((error) => setImageError(new Error(`draw failed: ${error.message}`)))
  }, [image, results, annotateOpts, analysis, elements, labels, lineWidth, scanlines])

  async function onImageFile(event) {
    const file = event.target.files?.[0]
    if (!file) return
    setImageError(null)
    try {
      // Decode once so re-runs don't re-decode.
      const bitmap = await createImageBitmap(file)
      setImage((previous) => {
        previous?.close()
        return bitmap
      })
    } catch (error) {
      setImageError(new Error(`could not decode ${file.name}: ${error.message}`))
    }
  }

  function onModelFile(event) {
    const file = event.target.files?.[0]
    // Allow re-picking the same file.
    event.target.value = ''
    if (!file) return
    setLocalModel(file)
    update({ model: LOCAL_MODEL })
  }

  function onReset() {
    // Keep the selected model.
    update({ ...DEFAULTS, model: settings.model })
  }

  // Lock pickers while busy; freeing mid-predict breaks it.
  const busy = loading || predicting
  const error = listError ?? loadError ?? predictError ?? imageError

  let status
  if (loading) status = `loading ${source.label}…`
  else if (error) status = error.message
  else if (model && image && !pixels) status = `ready · ${source.label} · frame could not be read back, no measurement`
  else if (model) status = `ready · ${source.label} · ${task} · ${ranOn}`
  else status = 'loading models…'

  return (
    <main>
      <ModelPicker
        models={models}
        value={settings.model}
        localModel={localModel}
        disabled={busy}
        onSelect={(key) => update({ model: key })}
        onLocalFile={onModelFile}
      />

      <p className={error ? 'status status-error' : 'status'}>{status}</p>

      <OptionsPanel
        settings={settings}
        names={names}
        task={task}
        busy={busy}
        onChange={update}
        onReset={onReset}
      />

      <input type="file" accept="image/*" disabled={busy} onChange={onImageFile} />

      {results && (
        <Results
          results={results}
          analysis={analysis}
          predicting={predicting}
          conf={settings.conf}
          keypointThreshold={settings.keypointThreshold}
          settings={settings}
        />
      )}

      <canvas ref={canvasRef} />

      {results && <TargetOverlay elements={analysis.elements} score={analysis.score} />}
    </main>
  )
}
